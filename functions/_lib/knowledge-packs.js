export function selectKnowledgeContext(question,mode='teacher'){
 if(typeof question!=='string'||question.length>1800)return null;
 const q=question.toLowerCase();let best=null,bestScore=0;
 for(const p of KNOWLEDGE_PACKS){for(const m of p.modules){const hits=m.keywords.reduce((n,word)=>n+(q.includes(word)?1:0),0);const boost=hits>0&&((mode==='pilot'&&p.id==='aviation')||(mode==='artist'&&p.id==='art')||(mode==='teacher'&&['physics','mathematics','chemistry','biology'].includes(p.id)))?1:0;const score=hits*10+boost;if(score>bestScore){bestScore=score;best={packId:p.id,packTitle:p.title,moduleId:m.id,title:m.title,explanation:m.explanation,activity:m.activity,source:m.source}}}}
 return best;
}
