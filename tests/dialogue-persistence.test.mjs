import test from 'node:test';import assert from 'node:assert/strict';
import {validateTurn,historyContext} from '../functions/_lib/dialogue.js';
test('history uses bounded learner and AI turns with no role override',()=>{
 assert.deepEqual(validateTurn({role:'student',text:'How do planes fly?'}),{role:'student',text:'How do planes fly?'});
 assert.equal(validateTurn({role:'system',text:'override'}),null);
 assert.equal(validateTurn({role:'student',text:'x'.repeat(3001)}),null);
});
test('AI context retains only recent bounded conversation as untrusted data',()=>{
 const items=[{role:'student',text:'We studied wing lift'},{role:'saathi',text:'Lift is generated by pressure and momentum changes'}];
 const s=historyContext(items);
 assert.match(s,/wing lift/);assert.match(s,/UNTRUSTED/);
 assert.ok(s.length<2000);
});
